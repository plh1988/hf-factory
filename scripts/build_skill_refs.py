"""Generate the capability skill's reference files from the code, so the skill never drifts from the engine.

    python scripts/build_skill_refs.py           # write the files
    python scripts/build_skill_refs.py --check   # exit 1 if any file is out of date (used by tests)

Writes, under skills/healthcare-capability-builder/:
  references/pack-schema.json   JSON Schema of the pack format (factory.data_engine.packs.model.Pack)
  references/generators.md      the building blocks: op, purpose, parameters
  examples/<pack>.yaml          the core packs, as worked examples
"""

from __future__ import annotations

import json
import sys
import typing
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "src"))

from factory.data_engine.packs import CORE_DIR  # noqa: E402
from factory.data_engine.packs.model import ANCHOR_FIELDS, ANCHOR_STAGE, Expr, Pack  # noqa: E402

SKILL = REPO / "skills" / "healthcare-capability-builder"
HEADER = "<!-- Generated by scripts/build_skill_refs.py from factory/data_engine/packs/model.py. Do not edit. -->\n"


def _type(info) -> str:
    """Readable parameter type for the generated table."""
    text = str(info.annotation)
    if "RowId" in text:  # an expression (or a list of them)
        kind = "list of Expr" if text.startswith("list[") else "number or Expr" if "float" in text.split(",")[0] else "Expr"
    else:
        kind = {"<class 'str'>": "string", "<class 'int'>": "integer", "<class 'float'>": "number",
                "list[typing.Any]": "list", "dict[str, typing.Any]": "object", "typing.Any": "any value",
                "list[float] | None": "list of numbers"}.get(text, text)
    return kind if info.is_required() else f"{kind}, optional"


def generators_md() -> str:
    ops = typing.get_args(typing.get_args(Expr)[0])
    lines = [HEADER, "# Building blocks", "",
             "Every column's `gen` (and `rows.when`) is one expression. Expressions nest: wherever a parameter takes an",
             "`Expr`, any building block can be used. Random building blocks take a `draw` name: the value is fixed by",
             "(seed, stream, row key, draw), so the same pack always produces the same rows, on any shard count.", "",
             "| op | Purpose | Parameters |", "|---|---|---|"]
    for m in ops:
        op = typing.get_args(m.model_fields["op"].annotation)[0]
        params = ", ".join(f"`{f.alias or name}`: {_type(f)}" for name, f in m.model_fields.items() if name != "op") or "-"
        doc = " ".join((m.__doc__ or "").split())
        lines.append(f"| `{op}` | {doc} | {params} |")
    lines += ["", "## Anchors", "", "| Anchor | Stage | Fields a pack can read with `{op: anchor, field: ...}` |", "|---|---|---|"]
    lines += [f"| `{a}` | {ANCHOR_STAGE[a]} | {', '.join(f'`{f}`' for f in fs)} |" for a, fs in ANCHOR_FIELDS.items()]
    lines += ["", "Column types: `string`, `bool`, `int`, `float`, `date`. The engine adds `is_synthetic`, `tenant_id` and",
              "`scenario_id` (P-01) to every row; rows inherit the anchor row's scenario tag.", ""]
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    files = {
        SKILL / "references" / "pack-schema.json": json.dumps(Pack.model_json_schema(by_alias=True), indent=2) + "\n",
        SKILL / "references" / "generators.md": generators_md(),
    }
    for p in sorted(CORE_DIR.glob("*.yaml")):
        files[SKILL / "examples" / p.name] = p.read_text(encoding="utf-8")
    return files


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs().items():
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(path.relative_to(REPO).as_posix())
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        print("out of date (run python scripts/build_skill_refs.py):", *stale, sep="\n  ")
        return 1
    print("written:" if stale else "up to date", *stale, sep="\n  ")
    return 0


if __name__ == "__main__":
    sys.exit(main())
