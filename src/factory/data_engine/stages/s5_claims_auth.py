"""Stage s5: claims (all claim entities), authorizations, and member accumulators derived from paid claims.

Sharded by member index: each member's claims and auths come from that member's own row streams.
Rules enforced while generating: R-02 coverage, R-03 auth for PA lines, R-04 network, R-08 pharmacy
detail, T-02 date order, T-03 auth clocks, T-04 auth covers DOS, F-01/F-02/F-05 money math, F-03 accumulators.

This module is the stage's ShardedGenerator (prepare, task_count, run_task); the work is in the s5 package:
inputs (what s5 reads), claims (ClaimBatch steps), auths (AuthBatch steps and writers), writers (claim entities).
"""

from __future__ import annotations

import numpy as np

from factory.data_engine import catalog
from factory.data_engine.context import GenContext
from factory.data_engine.stages.s5.auths import gen_auths
from factory.data_engine.stages.s5.claims import gen_claims
from factory.data_engine.stages.s5.inputs import Inputs, load_inputs
from factory.data_engine.stages.s5.writers import write_claims


def prepare(ctx: GenContext) -> Inputs:
    """Read members, plans and provider pools once for all tasks."""
    return load_inputs(ctx)


def task_count(ctx: GenContext, prep: Inputs) -> int:
    """One task per member shard (members as generated by s4)."""
    return len(ctx.shard_ranges(len(prep.members["member_id"])))


def run_task(ctx: GenContext, index: int, prep: Inputs) -> None:
    """Generate claims and authorizations for one shard of members. Safe to re-run (upserts on deterministic ids)."""
    lo, hi = ctx.shard_ranges(len(prep.members["member_id"]))[index]
    c = gen_claims(ctx, prep, slice(lo, hi))
    claim_auth = gen_auths(ctx, prep, c) if ctx.wants("auth_request") else np.full(c.n, None, dtype=object)
    write_claims(ctx, prep, c, claim_auth)


def run(ctx: GenContext) -> list[str]:
    """Run every task in this process (without the executor)."""
    prep = prepare(ctx)
    for i in range(task_count(ctx, prep)):
        run_task(ctx, i, prep)
    return [e for e in catalog.STAGE_ENTITIES["s5"] if ctx.wants(e)]
